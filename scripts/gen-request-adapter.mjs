import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = fs.readFileSync(path.join(root, 'frontend/bindings/cczjVideo/app/service/app.js'), 'utf8')
const policies = JSON.parse(fs.readFileSync(path.join(root, 'frontend/src/api/requestPolicies.json'), 'utf8'))
const names = [...source.matchAll(/^export function (\w+)\(/gm)].map(match => match[1])
const unknown = names.filter(name => !['read', 'write', 'isolated', 'refresh'].includes(policies[name]))
const removed = Object.keys(policies).filter(name => !names.includes(name))
if (unknown.length || removed.length) throw new Error(`Classify binding policies explicitly. Missing: ${unknown.join(', ')}; removed: ${removed.join(', ')}`)
const output = `// Generated by scripts/gen-request-adapter.mjs; policies are reviewed separately.
import './androidTransport'
import * as bindings from '../../bindings/cczjVideo/app/service/app'
import { requestPipelines, type RequestPolicy, type PipelineRequest } from './requestPipelines'
import policies from './requestPolicies.json'

function bind<A extends unknown[], T>(name: keyof typeof policies, call: (...args: A) => Promise<T>) {
  return (...args: A): PipelineRequest<T> => {
    // Refreshing a detail changes the database; cached reads must cross its barrier.
    const policy: RequestPolicy = name === 'LibraryItem' && args[1] === true ? 'refresh' : policies[name] as RequestPolicy
    return requestPipelines.run(name, policy, args, () => call(...args))
  }
}

${names.map(name => `export const ${name} = bind('${name}', bindings.${name})`).join('\n')}

export { normalizeApiError, ApiFailure, toApiFailure } from './errors'
export type { ApiError, ApiErrorCode } from './errors'
`
const target = path.join(root, 'frontend/src/api/app.ts')
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== output) throw new Error('Request adapter is stale; run node scripts/gen-request-adapter.mjs')
} else fs.writeFileSync(target, output)
console.log(`Request policies cover ${names.length} bindings`)

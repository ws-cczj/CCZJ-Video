func TestParseReleaseAsset(t *testing.T) {
	cases := []struct {
		name      string
		url       string
		wantOwner string
		wantRepo  string
		wantTag   string
		wantFile  string
		wantOK    bool
	}{
		{
			name: "direct", url: "https://github.com/ws-cczj/CCZJ-Video/releases/download/v2.2.1/cczjVideo-windows-amd64-2.2.1.exe",
			wantOwner: "ws-cczj", wantRepo: "CCZJ-Video", wantTag: "v2.2.1",
			wantFile: "cczjVideo-windows-amd64-2.2.1.exe", wantOK: true,
		},
		{
			name: "through a proxy prefix", url: "https://gh-proxy.org/https://github.com/ws-cczj/CCZJ-Video/releases/download/v2.2.1/a.zip",
			wantOwner: "ws-cczj", wantRepo: "CCZJ-Video", wantTag: "v2.2.1", wantFile: "a.zip", wantOK: true,
		},
		{
			name: "objects host is not a release asset", url: "https://objects.githubusercontent.com/foo/bar",
			wantOK: false,
		},
		{
			name: "missing file segment", url: "https://github.com/ws-cczj/CCZJ-Video/releases/download/v2.2.1",
			wantOK: false,
		},
		{
			name: "raw file url", url: "https://raw.githubusercontent.com/ws-cczj/CCZJ-Video/main/version.json",
			wantOK: false,
		},
		{
			name: "empty", url: "", wantOK: false,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			owner, repo, tag, file, ok := parseReleaseAsset(tc.url)
			if ok != tc.wantOK {
				t.Fatalf("ok = %v, want %v", ok, tc.wantOK)
			}
			if !ok {
				return
			}
			if owner != tc.wantOwner || repo != tc.wantRepo || tag != tc.wantTag || file != tc.wantFile {
				t.Fatalf("parsed %q %q %q %q", owner, repo, tag, file)
			}
		})
	}
}

func TestParseChecksums(t *testing.T) {
	const (
		lower  = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"
		upper  = "BBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBB"
		single = "cccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccc"
	)
	body := []byte(strings.Join([]string{
		"# generated by build/windows/package.ps1",
		"",
		lower + "  cczjVideo-windows-amd64-2.2.1.exe",
		// 大写摘要 + "./" 前缀：都要归一，否则清单大小写或写法一变就匹配不上。
		upper + "  ./App.zip",
		// 单个空格分隔（非 coreutils 规范写法）也接受：解析宽容，比对严格。
		single + " third.txt",
		"tooshort  bad.exe",
		"zzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzz bad2.exe",
		lower,
	}, "\r\n"))

	got := parseChecksums(body)

	want := map[string]string{
		"cczjvideo-windows-amd64-2.2.1.exe": lower,
		"app.zip":                           strings.ToLower(upper),
		"third.txt":                         single,
	}
	if len(got) != len(want) {
		t.Fatalf("expected %d entries, got %d: %v", len(want), len(got), got)
	}
	for name, digest := range want {
		if got[name] != digest {
			t.Errorf("%s = %q, want %q", name, got[name], digest)
		}
	}
}

func TestFetchReleaseChecksumsRejectsForeignRepoBeforeAnyRequest(t *testing.T) {
	// 校验清单必须来自本应用仓库；否则会拿别人发布的哈希来给产物背书。
	if _, err := fetchReleaseChecksums("evil", "CCZJ-Video", "v1.0.0"); err == nil {
		t.Fatal("expected foreign owner to be rejected")
	}
	if _, err := fetchReleaseChecksums(repoOwner, "other-repo", "v1.0.0"); err == nil {
		t.Fatal("expected foreign repo to be rejected")
	}
}


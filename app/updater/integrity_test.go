func TestUpdateStagingNameKeepsExtension(t *testing.T) {
	// 扩展名写死成 .exe 会让 InstallUpdate 按 exe 分支热替换，把 zip 字节盖进应用本体。
	cases := map[string]string{
		"https://github.com/ws-cczj/CCZJ-Video/releases/download/v2.2.1/app.EXE":   stagingPrefix + ".exe",
		"https://github.com/ws-cczj/CCZJ-Video/releases/download/v2.2.1/app.zip":   stagingPrefix + ".zip",
		"https://github.com/ws-cczj/CCZJ-Video/releases/download/v2.2.1/setup.msi": stagingPrefix + ".msi",
		// 认不出的扩展名一律 .bin：InstallUpdate 只会走"打开目录"分支，不会执行它。
		"https://github.com/ws-cczj/CCZJ-Video/releases/download/v2.2.1/app.tar.gz": stagingPrefix + ".gz",
		"https://example.com/whatever":                                              stagingPrefix + ".bin",
		"":                                                                          stagingPrefix + ".bin",
	}
	for url, want := range cases {
		if got := updateStagingName(url); got != want {
			t.Errorf("updateStagingName(%q) = %q, want %q", url, got, want)
		}
	}
}

func TestIsUpdateArtifact(t *testing.T) {
	appDir := getAppDir()
	exeName := getAppExeName()
	if appDir == "." || exeName == "" {
		t.Skip("cannot resolve the running executable in this environment")
	}
	exeBase := strings.TrimSuffix(exeName, filepath.Ext(exeName))

	cases := []struct {
		name string
		path string
		want bool
	}{
		{"staged exe", filepath.Join(appDir, stagingPrefix+".exe"), true},
		{"staged zip", filepath.Join(appDir, stagingPrefix+".zip"), true},
		{"staged bin", filepath.Join(appDir, stagingPrefix+".bin"), true},
		{"legacy underscore pattern", filepath.Join(appDir, exeBase+"_update.exe"), true},
		{"legacy numbered pattern", filepath.Join(appDir, exeBase+"_update(2).exe"), true},
		// 这个是攻击面：InstallUpdate 会 exec 传进来的路径。
		{"the running app itself", filepath.Join(appDir, exeName), false},
		{"unrelated file in app dir", filepath.Join(appDir, "calc.exe"), false},
		{"nested staged name", filepath.Join(appDir, "sub", stagingPrefix+".exe"), false},
		{"parent dir staged name", filepath.Join(appDir, "..", stagingPrefix+".exe"), false},
		{"absolute path outside", filepath.Join(filepath.VolumeName(appDir)+string(filepath.Separator), stagingPrefix+".exe"), false},
		{"empty", "", false},
		{"whitespace", "   ", false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := isUpdateArtifact(tc.path); got != tc.want {
				t.Fatalf("isUpdateArtifact(%q) = %v, want %v", tc.path, got, tc.want)
			}
		})
	}
}

func TestVerifyArtifact(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "payload.bin")
	content := []byte("cczj video update payload")
	if err := os.WriteFile(path, content, 0644); err != nil {
		t.Fatal(err)
	}
	sum := sha256.Sum256(content)
	good := hex.EncodeToString(sum[:])

	if err := verifyArtifact(path, good); err != nil {
		t.Fatalf("expected match, got %v", err)
	}
	// 大小写不敏感：清单里的摘要可能写成大写。
	if err := verifyArtifact(path, strings.ToUpper(good)); err != nil {
		t.Fatalf("expected case-insensitive match, got %v", err)
	}
	if err := verifyArtifact(path, strings.Repeat("0", 64)); err == nil {
		t.Fatal("expected mismatch to fail")
	}
	// 没有期望摘要时必须失败，不能"跳过校验"当成通过。
	if err := verifyArtifact(path, ""); err == nil {
		t.Fatal("expected empty expectation to fail")
	}
	if err := verifyArtifact(filepath.Join(dir, "missing.bin"), good); err == nil {
		t.Fatal("expected missing file to fail")
	}
}

func TestScanAlreadyDownloadedFindsStagedArtifact(t *testing.T) {
	dir := t.TempDir()
	// scanAlreadyDownloaded 只看真实应用目录，这里只验证命名规则与 glob 一致。
	staged := filepath.Join(dir, updateStagingName("https://github.com/ws-cczj/CCZJ-Video/releases/download/v2.2.1/app.zip"))
	if err := os.WriteFile(staged, []byte(strings.Repeat("x", 2048)), 0644); err != nil {
		t.Fatal(err)
	}
	matches, err := filepath.Glob(filepath.Join(dir, stagingPrefix+".*"))
	if err != nil || len(matches) != 1 {
		t.Fatalf("staged artifact is not discoverable by the scan pattern: %v %v", matches, err)
	}
	if matches[0] != staged {
		t.Fatalf("glob matched %v, want %v", matches[0], staged)
	}
}
